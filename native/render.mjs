import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { createHash } from 'node:crypto';
import { executable, run } from './sandbox.mjs';
import { scenePlan } from './scene-plan.mjs';
import { openCheckpoints } from './checkpoints.mjs';

export function createNativeRenderer({blenderPath,ffmpegPath,ffprobePath,bwrapPath='/usr/bin/bwrap',timeoutMs=600000,onDiagnostic,checkpointRoot}={}) {
  const blender=executable(blenderPath), ffmpeg=executable(ffmpegPath), ffprobe=executable(ffprobePath);
  if (!Number.isSafeInteger(timeoutMs) || timeoutMs<1000 || timeoutMs>600000) throw new Error('invalid_timeout');
  const sandboxBinary=process.platform==='linux'?executable(bwrapPath):undefined;
  const roots=[process.platform==='darwin'?path.resolve(blender,'../../..'):path.dirname(blender),process.platform==='darwin'?'/opt/homebrew':'/usr'];
  if (roots.some(r=>r==='/' || r===os.homedir())) throw new Error('unsafe_renderer_root');
  const checkpointDirectory=checkpointRoot?fs.realpathSync(checkpointRoot):undefined;
  let busy=false;
  return async (input,{signal=new AbortController().signal,checkpointKey}={}) => {
    const plan=scenePlan(input); signal.throwIfAborted();
    if(busy) throw new Error('native_renderer_busy');
    busy=true; let job,checkpoint,completed=false,resumedShots=0;
    try {
      job=fs.realpathSync(fs.mkdtempSync(path.join(os.tmpdir(),'kame-native-')));
      fs.chmodSync(job,0o700);
      const opts={job,roots,bwrapPath:sandboxBinary,onDiagnostic,signal:AbortSignal.any([signal,AbortSignal.timeout(timeoutMs)]),maxBytes:2*1024*1024};
      const script=fs.readFileSync(fileURLToPath(new URL('./render-scene.py',import.meta.url)));
      fs.writeFileSync(path.join(job,'render.py'),script,{mode:0o600});
      const frames=plan.shots.reduce((n,s)=>n+s.frames,0);
      const renderPlan=async(current,output)=>{
        fs.writeFileSync(path.join(job,'scene.json'),JSON.stringify(current),{mode:0o600});
        await run(blender,['--background','--factory-startup','--disable-autoexec','--threads','2','--python-exit-code','1','--python',path.join(job,'render.py'),'--',path.join(job,'scene.json')],opts);
        await run(ffmpeg,['-v','error','-nostdin','-framerate',String(plan.fps),'-i','frame-%04d.png','-frames:v',String(current.shots.reduce((n,s)=>n+s.frames,0)),'-c:v','libx264','-threads','2','-crf','18','-pix_fmt','yuv420p','-movflags','+faststart',output],opts);
      };
      if(checkpointDirectory){
        const fingerprint=createHash('sha256').update(JSON.stringify(plan)).update(script).update(fs.readFileSync(fileURLToPath(import.meta.url))).digest('hex');
        checkpoint=openCheckpoints(checkpointDirectory,checkpointKey,fingerprint,plan.shots.length);
        for(const [i,shot] of plan.shots.entries()){
          opts.signal.throwIfAborted();const name=`clip-${i}.mp4`,cached=checkpoint.get(i);
          if(cached){fs.writeFileSync(path.join(job,name),cached,{mode:0o600});resumedShots++;}
          else{
            await renderPlan({...plan,shots:[shot]},name);
            const clip=path.join(job,name);if(fs.statSync(clip).size>50*1024*1024)throw Error('native_output_size');
            checkpoint.put(i,fs.readFileSync(clip));
          }
          // Only files generated by this invocation, inside its private temp dir.
          for(const f of fs.readdirSync(job))if(/^frame-[0-9]+\.png$/.test(f))fs.unlinkSync(path.join(job,f));
        }
        fs.writeFileSync(path.join(job,'clips.txt'),plan.shots.map((_,i)=>`file 'clip-${i}.mp4'`).join('\n'),{mode:0o600});
        await run(ffmpeg,['-v','error','-nostdin','-f','concat','-safe','1','-i','clips.txt','-c','copy','-movflags','+faststart','video.mp4'],opts);
      }else await renderPlan(plan,'video.mp4');
      const info=JSON.parse(await run(ffprobe,['-v','error','-count_frames','-show_entries','stream=codec_type,codec_name,width,height,nb_read_frames,avg_frame_rate','-of','json','video.mp4'],opts));
      const v=info.streams?.[0];
      if(info.streams?.length!==1 || v.codec_type!=='video' || v.codec_name!=='h264' || v.width!==plan.width || v.height!==plan.height || Number(v.nb_read_frames)!==frames || v.avg_frame_rate!==`${plan.fps}/1`) throw new Error('native_output_contract_failed');
      const output=path.join(job,'video.mp4'),size=fs.statSync(output).size;
      if(size<1024 || size>50*1024*1024) throw new Error('native_output_size');
      const bytes=fs.readFileSync(output);
      completed=true;
      return {bytes,metadata:{engine:'kame-procedural-blender',resumedShots,externalModels:false,device:'CPU',width:plan.width,height:plan.height,fps:plan.fps,frames,durationMs:frames*1000/plan.fps,sha256:createHash('sha256').update(bytes).digest('hex'),planSha256:createHash('sha256').update(JSON.stringify(plan)).digest('hex')}};
    } finally { try {checkpoint?.close();if(completed)checkpoint?.remove();} finally {if(job)fs.rmSync(job,{recursive:true,force:true});busy=false;} }
  };
}
